def slug(s: str) -> str:
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", (s or "").lower())).strip("-")[:60] or "x"


def _gbp(v):
    return f"£{round(v):,}" if isinstance(v, (int, float)) else "value not stated"


