def canonical_sector(t: dict) -> str | None:
    """One sector label per CPV division, regardless of which feed it came from
    — stops the two sources' different CPV text creating duplicate pages."""
    div = (t.get("cpv2") or "")[:2]
    return CPV_DIVISIONS.get(div) or t.get("sector")

