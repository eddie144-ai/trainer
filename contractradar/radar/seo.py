"""SEO engine — generate programmatic landing pages from the live tender data.

Distribution is the whole game, and the only channel is content/SEO. This turns
the live contract database into hundreds of genuinely useful long-tail pages —
one per sector, region and major buyer — each listing real current opportunities
and funnelling to the BidBeacon tool. Every page is regenerated by the nightly
cron, so they stay fresh (stale listings are what gets auto-pages de-indexed).

    PYTHONPATH=. python3 -m radar.seo            # reads site/tenders.json -> site/seo/

Quality guardrails (so Google treats these as useful, not thin/spam):
  - a page is only generated when it has at least MIN_ITEMS real live listings;
  - each intro states real, page-specific facts (counts, value range, top buyers);
  - pages interlink, and all link to the live tool.
"""
