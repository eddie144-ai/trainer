def md_to_html(md: str) -> str:
    """Minimal Markdown → HTML for our own controlled article content:
    #/##/### headings, paragraphs, - lists, 1. lists, **bold**, [text](url), ---."""
    def inline(s):
        s = html.escape(s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a href="\2">\1</a>', s)
        return s
    out, lst = [], None
    def close():
        nonlocal lst
        if lst: out.append(f"</{lst}>"); lst = None
    for raw in md.splitlines():
        line = raw.rstrip()
        if not line: close(); continue
        if line == "---": close(); out.append("<hr>"); continue
        m = re.match(r"(#{1,3}) (.+)", line)
        if m: close(); out.append(f"<h{len(m.group(1))}>{inline(m.group(2))}</h{len(m.group(1))}>"); continue
        m = re.match(r"- (.+)", line)
        if m:
            if lst != "ul": close(); out.append("<ul>"); lst = "ul"
            out.append(f"<li>{inline(m.group(1))}</li>"); continue
        m = re.match(r"\d+\. (.+)", line)
        if m:
            if lst != "ol": close(); out.append("<ol>"); lst = "ol"
            out.append(f"<li>{inline(m.group(1))}</li>"); continue
        close(); out.append(f"<p>{inline(line)}</p>")
    close()
    return "\n".join(out)


