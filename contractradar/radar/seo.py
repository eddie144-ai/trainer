def _render_content(subdir: str, related):
    """Render content/<subdir>/*.md (first line '# Title', second line '> desc')
    into site/seo/<subdir>/*.html. Returns [(title, 'seo/<subdir>/<slug>.html')]."""
    src = ROOT / "content" / subdir
    if not src.exists():
        return []
    (OUT / subdir).mkdir(parents=True, exist_ok=True)
    links = []
    for md_file in sorted(src.glob("*.md")):
        lines = md_file.read_text().splitlines()
        title = lines[0].lstrip("# ").strip()
        desc = lines[1].lstrip("> ").strip() if len(lines) > 1 and lines[1].startswith(">") else title
        body = md_to_html("\n".join(lines[2:] if desc != title else lines[1:]))
        (OUT / subdir / f"{md_file.stem}.html").write_text(
            article_page(f"{title} | BidBeacon", desc, f"<h1>{html.escape(title)}</h1>\n{body}",
                         related, depth=2))
        links.append((title, f"seo/{subdir}/{md_file.stem}.html"))
    return links


def build() -> dict:
    tenders = json.load(open(SITE / "tenders.json"))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "sector").mkdir(exist_ok=True)
    (OUT / "region").mkdir(exist_ok=True)
    (OUT / "buyer").mkdir(exist_ok=True)

    def group(key):
        g = {}
        for t in tenders:
            k = key(t)
            if k:
                g.setdefault(k, []).append(t)
        return {k: v for k, v in g.items() if len(v) >= MIN_ITEMS}

    REGION = {"ne": "Aberdeen & North-East Scotland", "scot": "Scotland", "uk": "UK-wide"}
    def region_key(t):
        n = (t.get("nuts") or "").upper(); c = (t.get("country") or "").upper()
        if n.startswith("UKM5"): return "ne"
        if n.startswith("UKM"): return "scot"
        if n == "UK" or c in ("GB", "UNITED KINGDOM", ""): return "uk"
        return None

    sectors = group(canonical_sector)
    regions = group(region_key)
    buyers = dict(sorted(group(lambda t: t.get("buyer")).items(),
                         key=lambda kv: -len(kv[1]))[:12])

    # related links shared across pages
    rel_sectors = [(f"{s} contracts", f"sector/{slug(s)}.html") for s in list(sectors)[:8]]
    rel_regions = [(REGION[r], f"region/{r}.html") for r in regions]

    def valrange(items):
        vals = [t["value"] for t in items if isinstance(t.get("value"), (int, float))]
        return f"{_gbp(min(vals))}–{_gbp(max(vals))}" if vals else "a range of values"

    n = 0
    for s, items in sectors.items():
        top = ", ".join(sorted({t["buyer"] for t in items if t.get("buyer")})[:3])
        lede = (f"{len(items)} open {s.lower()} public-sector contracts in Scotland and the UK, "
                f"worth {valrange(items)}. Buyers include {top}. Updated daily.")
        (OUT / "sector" / f"{slug(s)}.html").write_text(page(
            f"{s} public contracts in Scotland — live tenders | BidBeacon",
            lede, f"{s} public contracts", lede, items,
            rel_regions + [(f"{x} contracts", f"sector/{slug(x)}.html") for x in sectors if x != s][:6],
            depth=2)); n += 1

    for r, items in regions.items():
        lede = (f"{len(items)} open public-sector contracts for {REGION[r]}, across sectors from "
                f"construction to IT, worth {valrange(items)}. Updated daily from official sources.")
        (OUT / "region" / f"{r}.html").write_text(page(
            f"Public sector contracts — {REGION[r]} | BidBeacon",
            lede, f"Public contracts: {REGION[r]}", lede, items, rel_sectors, depth=2)); n += 1

    for b, items in buyers.items():
        lede = (f"{len(items)} open tenders currently advertised by {b}, worth {valrange(items)}. "
                f"Track new ones automatically with BidBeacon.")
        (OUT / "buyer" / f"{slug(b)}.html").write_text(page(
            f"{b} — open tenders & contracts | BidBeacon",
            lede, f"{b}: open tenders", lede, items, rel_sectors + rel_regions, depth=2)); n += 1

    # cornerstone guides + legal pages (from content/*.md)
    guide_links = _render_content("guides", rel_sectors + rel_regions)
    legal_links = _render_content("legal", [])
    n += len(guide_links) + len(legal_links)

    # hub index
    links = []
    hub_groups = [("By sector", [(s, f"sector/{slug(s)}.html") for s in sectors]),
                  ("By region", [(REGION[r], f"region/{r}.html") for r in regions]),
                  ("By buyer", [(b, f"buyer/{slug(b)}.html") for b in buyers])]
    if guide_links:
        hub_groups.append(("Guides", [(t, h.replace("seo/", "", 1)) for t, h in guide_links]))
    for label, pages_ in hub_groups:
        links.append(f"<h2 style='font-size:1rem;margin:20px 0 6px'>{label}</h2>")
        links.append("<nav class='related' style='border:none;margin:0;padding:0'>" +
                      "".join(f'<a href="{href}">{html.escape(t)}</a>' for t, href in pages_) + "</nav>")
    hub = page("Live UK & Scottish public contracts by sector, region & buyer | BidBeacon",
               "Browse live public-sector contract opportunities across Scotland and the UK by sector, region and buyer.",
               "Live public contracts, organised",
               f"{len(tenders)} open public-sector opportunities, grouped so you can find the ones that fit. "
               "All data live from Public Contracts Scotland and Contracts Finder.",
               [], [], depth=1).replace("<ul class=\"list\"></ul>", "".join(links))
    (OUT / "index.html").write_text(hub); n += 1

    # sitemap.xml + robots.txt (set BIDBEACON_BASE to your domain at deploy)
    import os
    base = os.environ.get("BIDBEACON_BASE", "https://bidbeacon.co.uk").rstrip("/")
    urls = [f"{base}/bidbeacon.html", f"{base}/seo/index.html"]
    urls += [f"{base}/seo/{p.relative_to(OUT).as_posix()}"
             for p in OUT.rglob("*.html") if p.name != "index.html"]
    today = date.today().isoformat()
    sm = ['<?xml version="1.0" encoding="UTF-8"?>',
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u in urls:
        sm.append(f"<url><loc>{html.escape(u)}</loc><lastmod>{today}</lastmod></url>")
    sm.append("</urlset>")
    (SITE / "sitemap.xml").write_text("\n".join(sm))
    (SITE / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {base}/sitemap.xml\n")
    return {"pages": n, "sectors": len(sectors), "regions": len(regions),
            "buyers": len(buyers), "guides": len(guide_links), "sitemap_urls": len(urls)}


if __name__ == "__main__":
    print(json.dumps(build(), indent=2))
